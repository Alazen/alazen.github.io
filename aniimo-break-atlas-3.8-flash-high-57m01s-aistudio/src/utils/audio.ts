export function playBreakShatterSound(): void {
  if (isMuted) return;
  const ctx = getAudioContext();
  if (!ctx) return;

  try {
    // Multi-layer explosive glass shatter effect
    const freqs = [350, 700, 1050, 1400, 2100];
    freqs.forEach((freq, idx) => {
      const osc = ctx.createOscillator();
      const gain = ctx.createGain();

      osc.type = idx % 2 === 0 ? 'sawtooth' : 'triangle';
      osc.frequency.setValueAtTime(freq, ctx.currentTime + idx * 0.02);
      osc.frequency.exponentialRampToValueAtTime(freq * 0.4, ctx.currentTime + 0.35 + idx * 0.03);

      gain.gain.setValueAtTime(0.12 / (idx + 1), ctx.currentTime + idx * 0.02);
      gain.gain.exponentialRampToValueAtTime(0.0001, ctx.currentTime + 0.45);

      osc.connect(gain);
      gain.connect(ctx.destination);

      osc.start(ctx.currentTime + idx * 0.02);
      osc.stop(ctx.currentTime + 0.45);
    });
  } catch {
    // Ignore
  }
}

